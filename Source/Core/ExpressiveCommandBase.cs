using Open.Database.Extensions.Synchronous;

namespace Open.Database.Extensions;

/// <summary>
/// Represents the base class of the expressive commands, for use with
/// <see cref="IDbConnection"/> and <see cref="IDbCommand"/> types.
/// </summary>
/// <remarks>
/// For a command you run more than once, a <see cref="DbQuery"/> definition is the recommended route and the fastest: it scans its text once and
/// holds its parameters in one array. This builder is for a command you build and run once.
/// A command whose text is a string literal (interned text) sends a parameter name written without its <c>@</c> under the text's own spelling.
/// </remarks>
/// <typeparam name="TConnection">The type of the connection to be used.</typeparam>
/// <typeparam name="TCommand">The type of the commands generated by the connection.</typeparam>
/// <typeparam name="TReader">The type of reader created by the command.</typeparam>
/// <typeparam name="TDbType">The DB type enum to use for parameters.</typeparam>
/// <typeparam name="TThis">The type of the derived class, so that the chaining methods return it.</typeparam>
public abstract partial class ExpressiveCommandBase<TConnection, TCommand, TReader, TDbType, TThis>
		: IExecuteCommandSync<TCommand>, IExecuteReaderSync<TReader>
		where TConnection : class, IDbConnection
		where TCommand : class, IDbCommand
		where TReader : class, IDataReader
		where TDbType : struct
		where TThis : ExpressiveCommandBase<TConnection, TCommand, TReader, TDbType, TThis>
{

	/// <summary>
	/// Gets the pool that connections are taken from.
	/// </summary>
	/// <value>The pool that connections are taken from.</value>
	/// <remarks>
	/// A command built on a bare connection gets a provider around that
	/// connection, made on first use.
	/// </remarks>
	protected IDbConnectionPool<TConnection> ConnectionProvider
		=> _poolOrConnection as IDbConnectionPool<TConnection> ?? (EnsureOptions().Provider ??= DbConnectionProvider.Create((TConnection)_poolOrConnection));

	/// <summary>
	/// The pool to take connections from or, for a command built from a bare
	/// connection, the connection itself.
	/// </summary>
	/// <remarks>
	/// Running a command on a bare connection needs no pool wrapper object.
	/// </remarks>
	readonly object _poolOrConnection;
	/// <summary>
	/// Whether a run holds the single connection (see <c>EnterDirect</c>):
	/// 1 while it does, otherwise 0.
	/// </summary>
	int _busy;

	/// <summary>
	/// Whether a parameter added by <c>AddParam(value)</c> or
	/// <c>AddParams(object)</c> has a name that is worked out in every run.
	/// </summary>
	/// <remarks>It is never cleared.</remarks>
	bool _hasDerivedParams;

	/// <summary>
	/// The command being set up on this thread, or <see langword="null"/>.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Set only during the one synchronous stretch in
	/// <c>PrepareDerived</c>, for a command with derived names or written names that the text spells differently.
	/// It is per thread, so two threads running one command never see each
	/// other's list.
	/// </para>
	/// <para>
	/// <see cref="Params"/> returns the send list to the command's own hook
	/// (<see cref="AddParams(TCommand)"/>) and to nobody else.
	/// </para>
	/// </remarks>
	[ThreadStatic]
	static object? _preparing;

	/// <summary>
	/// The list of what this run sends under the resolved names, on this
	/// thread, while <see cref="_preparing"/> is set.
	/// </summary>
	[ThreadStatic]
	static List<Param>? _sendList;

	/// <summary>
	/// The list kept for the next run on this thread.
	/// It is empty, so it holds no values.
	/// </summary>
	[ThreadStatic]
	static List<Param>? _spareList;

	/// <summary>
	/// The rarely-set members of a command.
	/// </summary>
	/// <remarks>
	/// They live in a block that is only allocated when one is set, so the
	/// usual <c>conn.Command(sql)</c> object, which is allocated on every
	/// call, stays small.
	/// </remarks>
	private protected sealed class CommandOptions
	{
		public IDbTransaction? Transaction;
		public IDbConnectionPool<TConnection>? Provider;
		public CancellationToken CancellationToken;
		public ushort Timeout = CommandTimeout.DEFAULT_SECONDS;
		public bool AsyncReads;
	}

	private protected CommandOptions? _options;
	private protected CommandOptions EnsureOptions() => _options ??= new();

	/// <summary>
	/// Gets the transaction the command runs in, or <see langword="null"/>
	/// when it was not given one.
	/// </summary>
	/// <value>
	/// The transaction the command runs in, or <see langword="null"/>
	/// when it was not given one.
	/// </value>
	protected IDbTransaction? Transaction => _options?.Transaction;

	/// <summary>
	/// Initializes a new instance that takes its connections from a
	/// connection pool.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorPool']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		IDbConnectionPool<TConnection> connectionPool,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
	{
		_poolOrConnection = connectionPool ?? throw new ArgumentNullException(nameof(connectionPool));
		Command = command ?? throw new ArgumentNullException(nameof(command));
		if (string.IsNullOrWhiteSpace(command)) throw new ArgumentException("Cannot be null or whitespace.", nameof(command));
		Contract.EndContractBlock();

		Type = type;
		if (@params is not null) _params = @params.ToList();
	}

	/// <summary>
	/// Initializes a new instance that creates a new connection from a
	/// connection factory for each execution.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorFactory']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		IDbConnectionFactory<TConnection> connFactory,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
		: this((connFactory ?? throw new ArgumentNullException(nameof(connFactory))).AsPool(), type, command, @params)
	{
	}

	/// <summary>
	/// Initializes a new instance that invokes a function to create a new
	/// connection for each execution.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorFunc']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		Func<TConnection> connFactory,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
		: this((connFactory ?? throw new ArgumentNullException(nameof(connFactory))).AsPool(), type, command, @params)
	{
	}

	/// <summary>
	/// Initializes a new instance that executes on an existing connection,
	/// optionally within a transaction.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorConnectionTx']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		TConnection connection,
		IDbTransaction? transaction,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
	{
		_poolOrConnection = connection ?? throw new ArgumentNullException(nameof(connection));
		if (transaction is not null) EnsureOptions().Transaction = transaction;
		Command = command ?? throw new ArgumentNullException(nameof(command));
		if (string.IsNullOrWhiteSpace(command)) throw new ArgumentException("Cannot be null or whitespace.", nameof(command));
		Contract.EndContractBlock();

		Type = type;
		if (@params is not null) _params = @params.ToList();
	}

	/// <summary>
	/// Initializes a new instance that executes on an existing connection.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorConnection']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		TConnection connection,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
		: this(connection, null, type, command, @params)
	{
	}

	/// <summary>
	/// Initializes a new instance that executes within a transaction, on the
	/// transaction's connection.
	/// </summary>
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorTx']/*" />
	/// <include file="Commands.docs.xml" path="docs/members[@name='ctorCommon']/*" />
	protected ExpressiveCommandBase(
		IDbTransaction transaction,
		CommandType type,
		string command,
		IEnumerable<Param>? @params)
		: this(
			(TConnection)(transaction ?? throw new ArgumentNullException(nameof(transaction))).Connection!,
			transaction, type, command, @params)
	{
	}

	/// <summary>
	/// Gets or sets the command text, or the stored procedure name when
	/// <see cref="Type"/> is <see cref="CommandType.StoredProcedure"/>.
	/// </summary>
	/// <value>The command text, or the stored procedure name.</value>
	public string Command { get; set; }

	/// <summary>
	/// Gets or sets how <see cref="Command"/> is interpreted.
	/// </summary>
	/// <value>One of the <see cref="CommandType"/> values that says how <see cref="Command"/> is interpreted.</value>
	public CommandType Type { get; set; }

	/// <summary>
	/// Gets the parameters to apply to the command before execution.
	/// </summary>
	/// <value>The list of parameters that were added to the command.</value>
	/// <remarks>
	/// Running the command never changes this list:
	/// it holds what was added, in order, under the names as added.
	/// The names an <c>AddParam(value)</c> or <c>AddParams(object)</c>
	/// parameter is sent under are worked out in every run
	/// (they can differ per database)
	/// and are visible in <c>Execute(command =&gt; ...)</c>
	/// on the provider's command.
	/// </remarks>
	public List<Param> Params => ActiveSendList ?? (_params ??= new(ScannedCount()));

	/// <summary>
	/// The list of what this run sends, while this command is being set up
	/// on this thread; otherwise <see langword="null"/>.
	/// </summary>
	/// <remarks>
	/// Every read of <see cref="Params"/> reads one thread-static field.
	/// </remarks>
	List<Param>? ActiveSendList
		=> ReferenceEquals(_preparing, this)
			? _sendList
			: null;

	/// <summary>
	/// The parameters that were added.
	/// </summary>
	/// <remarks>
	/// Most commands have no params, so the list is only created when one is
	/// added.
	/// </remarks>
	List<Param>? _params;

	/// <summary>
	/// Gets or sets the command timeout, in seconds.
	/// </summary>
	/// <value>The command timeout, in seconds.</value>
	/// <remarks>
	/// The default is 60 seconds.
	/// </remarks>
	public ushort Timeout
	{
		get => _options?.Timeout ?? CommandTimeout.DEFAULT_SECONDS;
		set
		{
			if (value == CommandTimeout.DEFAULT_SECONDS && _options is null) return;
			EnsureOptions().Timeout = value;
		}
	}

	/// <summary>
	/// Creates the expected command type from the connection provided.
	/// </summary>
	/// <param name="connection">The connection to create the command from.</param>
	/// <returns>The new command to use.</returns>
	/// <exception cref="InvalidCastException">
	/// The connection creates a command that is not a <typeparamref name="TCommand"/>.
	/// </exception>
	protected TCommand PrepareCommand(TConnection connection)
	{
		IDbCommand cmd = connection.CreateCommand(Type, Command, Timeout);

		// A command that cannot be set up is never returned, so nobody else can dispose it.
		try
		{
			if (cmd is not TCommand c)
				throw new InvalidCastException($"Actual command type ({cmd.GetType()}) is not compatible with expected command type ({typeof(TCommand)}).");
			if (Transaction != null)
				c.Transaction = Transaction;
			if ((ActiveSendList ?? _params) is { Count: > 0 }) AddParams(c);
			return c;
		}
		catch
		{
			cmd.Dispose();
			throw;
		}
	}

	/// <summary>
	/// Gets or sets the cancellation token used with the methods that support
	/// one.
	/// </summary>
	/// <value>
	/// The cancellation token of the command,
	/// or <see cref="CancellationToken.None"/> when none was set.
	/// </value>
	/// <remarks>
	/// A terminal that takes a token of its own uses it together with this
	/// one; either cancels the call.
	/// </remarks>
	public CancellationToken CancellationToken
	{
		get => _options?.CancellationToken ?? CancellationToken.None;
		set
		{
			if (!value.CanBeCanceled && _options is null) return;
			EnsureOptions().CancellationToken = value;
		}
	}

	CancellationToken IExecuteReader.CancellationToken => CancellationToken;

	/// <summary>
	/// Sets the cancellation token.
	/// </summary>
	/// <param name="token">The token to use.</param>
	/// <returns>This instance for use in method chaining.</returns>
	/// <seealso cref="CancellationToken"/>
	public TThis UseCancellationToken(CancellationToken token)
	{
		CancellationToken = token;
		return (TThis)this;
	}

	#region AddParam

	/// <summary>
	/// Adds a parameter to the params list.
	/// </summary>
	/// <param name="param">The parameter to add.</param>
	/// <returns>This instance for use in method chaining.</returns>
	protected TThis AddParam(Param param)
	{
		Params.Add(param);
		return (TThis)this;
	}

	/// <summary>
	/// Adds a parameter to the params list.
	/// </summary>
	/// <param name="name">The name of the parameter.</param>
	/// <param name="value">The value of the parameter.</param>
	/// <param name="type">The database type of the parameter.</param>
	/// <param name="direction">The direction of the parameter.</param>
	/// <returns>This instance for use in method chaining.</returns>
	/// <remarks>
	/// A <see langword="null"/> <paramref name="value"/> passed to an overload
	/// whose argument has a static type
	/// (a nullable value type, or a <see cref="string"/>)
	/// is sent with the database type of that type,
	/// the same choice <c>AddParams</c> makes for a NULL member.
	/// A <paramref name="type"/> you pass always wins.
	/// The <see cref="object"/> overloads have no type to use,
	/// and neither does a call that gives the direction by position
	/// (<c>AddParam(name, value, ParameterDirection.Input)</c>):
	/// pass a database type, or name the direction
	/// (<c>direction: ...</c>).
	/// </remarks>
	/// <exception cref="ArgumentNullException"><paramref name="name"/> is <see langword="null"/>.</exception>
	/// <exception cref="ArgumentException"><paramref name="name"/> is empty or white space.</exception>
	public TThis AddParam(string name, object? value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam(string name, object? value, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, null, direction));

	/// <typeparam name="T">The type of the value.</typeparam>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam<T>(string name, T? value, TDbType? type = null, ParameterDirection direction = ParameterDirection.Input)
		where T : struct
		=> AddParam(Param.Typed(name, value, typeof(T), type, direction));

	/// <summary>
	/// Adds a parameter with an <see cref="int"/> value.
	/// </summary>
	/// <remarks>
	/// A literal 0 converts implicitly to any enum, so without this overload
	/// a call like <c>AddParam("id", 0)</c> would bind to the type-only or
	/// direction-only overloads and silently add a parameter with no value.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, int value, TDbType? type = null, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <summary>
	/// Adds a parameter with a <see cref="long"/> value.
	/// </summary>
	/// <remarks>
	/// A literal 0 converts implicitly to any enum, so without this overload
	/// a call like <c>AddParam("id", 0L)</c> would bind to the type-only or
	/// direction-only overloads and silently add a parameter with no value.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, long value, TDbType? type = null, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <summary>
	/// Adds a parameter with a <see cref="char"/> value.
	/// </summary>
	/// <remarks>
	/// A <see cref="char"/> converts implicitly to <see cref="int"/>, so
	/// without this overload <c>AddParam("x", 'c')</c> would send the
	/// character code (99), not the character
	/// (as it did before the <see cref="int"/> overload existed).
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, char value, TDbType? type = null, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam(string name, string? value, TDbType? type = null, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(Param.Typed(name, value, typeof(string), type, direction));

	/// <summary>
	/// Adds a parameter with an <see cref="int"/> value and a required
	/// database type.
	/// </summary>
	/// <remarks>
	/// With the optional-type overloads alone, <c>AddParam("id", id, SqlDbType.Int)</c>
	/// matches them and the <see cref="object"/> overload with neither better
	/// (one has the exact value type, the other the exact database type),
	/// which compilers report as ambiguous (CS0121).
	/// A required type of the exact enum type makes these the best match.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, int value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <summary>
	/// Adds a parameter with a <see cref="long"/> value and a required
	/// database type.
	/// </summary>
	/// <remarks>
	/// The type is required for the reason given for
	/// <see cref="AddParam(string, int, TDbType, ParameterDirection)"/>.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, long value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <summary>
	/// Adds a parameter with a <see cref="char"/> value and a required
	/// database type.
	/// </summary>
	/// <remarks>
	/// A <see cref="char"/> has its own overload so that it is sent as a
	/// character, not widened to an <see cref="int"/> and sent as its code.
	/// The type is required for the reason given for
	/// <see cref="AddParam(string, int, TDbType, ParameterDirection)"/>.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, char value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, value, type, direction));

	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam(string name, string? value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(Param.Typed(name, value, typeof(string), type, direction));

	/// <typeparam name="T">The type of the value.</typeparam>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam<T>(string name, T? value, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		where T : struct
		=> AddParam(Param.Typed(name, value, typeof(T), type, direction));

	/// <summary>
	/// Adds an input parameter with a string value, named as you write it.
	/// </summary>
	/// <param name="name">The name of the parameter.</param>
	/// <param name="value">The value of the parameter.</param>
	/// <remarks>
	/// Compilers older than C# 13 ignore <c>OverloadResolutionPriority</c>,
	/// so without this overload they would bind
	/// <c>AddParam("name", someString)</c> to
	/// <see cref="AddParam{T}(T, string?)"/>, which would read the name as
	/// the value and send the parameter under the text of the second argument.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::param) and not(self::summary)]"/>
	public TThis AddParam(string name, string? value)
		=> AddParam(name, value, null, ParameterDirection.Input);

	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)"/>
	public TThis AddParam(string name, TDbType type, ParameterDirection direction = ParameterDirection.Input)
		=> AddParam(new(name, null, type, direction));

	/// <summary>
	/// Adds a parameter with no value and the direction given.
	/// </summary>
	/// <remarks>
	/// The direction is required so that a single argument never binds here:
	/// <c>AddParam(filter.Name)</c> with a string argument must reach
	/// <see cref="AddParam{T}(T, string?)"/>, not be read as a parameter name.
	/// </remarks>
	/// <inheritdoc cref="AddParam(string, object, TDbType, ParameterDirection)" path="/*[not(self::summary)]"/>
	public TThis AddParam(string name, ParameterDirection direction)
		=> AddParam(new(name, null, null, direction));

	/// <summary>
	/// Adds an input parameter whose name is taken from the argument expression: <c>AddParam(filter.AuthorId)</c> adds a parameter named for <c>AuthorId</c>.
	/// </summary>
	/// <remarks>
	/// <para>The argument must be a variable or a chain of member accesses (properties and fields alike): <c>startDate</c>, <c>filter.AuthorId</c>, <c>post.Author.Id</c>.
	/// Anything else (a call, an index, an operator, a literal) throws <see cref="ArgumentException"/>: use <see cref="AddParam(string, object?, ParameterDirection)"/> and name the parameter.</para>
	/// <para>The name is settled when the command executes. The real parameter names are:</para>
	/// <list type="bullet">
	/// <item>for a stored procedure, the names the provider reports for the procedure;</item>
	/// <item>
	/// for a text command, the <c>@name</c> markers found in its SQL text
	/// (not those inside a string, a quoted identifier or a comment,
	/// and not <c>@@system</c> variables).
	/// </item>
	/// </list>
	/// <para>The argument is matched to one of them, trying in turn:</para>
	/// <list type="number">
	/// <item>exactly;</item>
	/// <item>ignoring case;</item>
	/// <item>ignoring case and underscores, so <c>AuthorId</c> finds <c>@author_id</c>;</item>
	/// <item>
	/// failing those, for the same argument, after removing one common
	/// parameter prefix from the real name
	/// (<c>p_</c>, <c>in_</c>, <c>i_</c>, <c>prm_</c>, <c>par_</c>, <c>v_</c>,
	/// or a lone <c>p</c> before a capital letter),
	/// so <c>Author</c> finds <c>@p_author</c> and <c>@pAuthor</c>.
	/// </item>
	/// </list>
	/// <para>
	/// A field prefix on the last member (<c>m_</c>, <c>s_</c> or <c>_</c>) is
	/// also tried without.
	/// A chain tries its more specific endings first:
	/// <c>post.Author.Id</c> tries <c>postAuthorId</c>, <c>AuthorId</c>, then <c>Id</c>.
	/// A name that matches nothing, matches two parameters at one tier,
	/// or is claimed by two arguments throws
	/// <see cref="InvalidOperationException"/> that says what you wrote and,
	/// when the names are known, what the procedure declares.
	/// </para>
	/// <para>
	/// The names are remembered for five minutes per connection factory, pool
	/// or connection.
	/// When an argument matches none of the remembered names they are read
	/// again once before that throws, and so are they before a member of an
	/// <c>AddParams</c> object that they do not declare is dropped
	/// (once per set of names: a second look that still lacks the member is
	/// remembered); nothing else triggers a read, so an ambiguity, a collision
	/// and a less specific match are decided from the remembered names.
	/// </para>
	/// <para>
	/// Where the real names are not available (a text command with no
	/// <c>@name</c> marker, or a provider that does not supply them) the last
	/// member is used as written.
	/// </para>
	/// </remarks>
	/// <typeparam name="T">The type of the value.</typeparam>
	/// <param name="value">The value of the parameter. A <see langword="null"/> is sent as a database null.</param>
	/// <param name="expression">The text of the argument, supplied by the compiler. Do not pass it.</param>
	/// <returns>This instance for use in method chaining.</returns>
	/// <exception cref="ArgumentException">A parameter name cannot be derived from the argument.</exception>
	/// <exception cref="InvalidOperationException">
	/// When the command executes: the name matches no parameter, matches two at one tier, or collides with another argument.
	/// </exception>
	[OverloadResolutionPriority(-1)]
	public TThis AddParam<T>(T value, [CallerArgumentExpression(nameof(value))] string? expression = null)
		=> AddDerivedParam(value, expression, typeof(T));

	/// <summary>
	/// Conditionally adds an input parameter whose name is taken from the argument expression. See <see cref="AddParam{T}(T, string?)"/>.
	/// </summary>
	/// <typeparam name="T">The type of the value.</typeparam>
	/// <include file="Commands.docs.xml" path="docs/members[@name='condition']/*" />
	/// <param name="value">The value of the parameter.</param>
	/// <param name="expression">The text of the argument, supplied by the compiler. Do not pass it.</param>
	/// <returns>This instance for use in method chaining.</returns>
	/// <exception cref="ArgumentException">A parameter name cannot be derived from the argument (checked even when <paramref name="condition"/> is <see langword="false"/>).</exception>
	[OverloadResolutionPriority(-1)]
	public TThis AddParamIf<T>(bool condition, T value, [CallerArgumentExpression(nameof(value))] string? expression = null)
		=> condition ? AddDerivedParam(value, expression, typeof(T)) : CheckDerivable(expression);

	/// <summary>
	/// Adds the public properties and fields of <paramref name="source"/> as parameters. A member the stored procedure declares is sent under the procedure's real name (<c>AuthorId</c> as <c>@author_id</c>), a member it does not declare is skipped,
	/// and where the procedure's names are not known (a text command with no <c>@name</c> marker, or a provider that does not supply them) every member is sent under its own name.
	/// </summary>
	/// <remarks>
	/// <para>Each member is matched to the stored procedure's real parameter names the same way as <see cref="AddParam{T}(T, string?)"/>.
	/// When the real names are known, a member that the procedure does not declare is not sent, so one object can serve several procedures
	/// (a member that the remembered names lack makes them be read once more first, in case the procedure gained that parameter since: once per remembered set, so a member the procedure never takes costs one extra read, not one per run); parameters the procedure declares that no member matches are left to default values or to explicit <c>AddParam</c> calls.
	/// A parameter you add with <c>AddParam</c>, by name or from an argument, wins over a member that resolves to the same name.</para>
	/// <para>Every public readable property and field is read when this method is called, whether or not the procedure declares it, so a getter that throws or loads lazily runs then. Static members and indexers are ignored.
	/// The members are those of the static type <typeparamref name="T"/>, not of the object's runtime type: an interface adds only its own. The one exception is <see cref="object"/>: a variable typed <see cref="object"/>, or the result of a <c>Func&lt;T, object&gt;</c>, has no members of its own, so the members of its runtime type are used.
	/// There, the members of each type are found once and remembered. Nested objects are not flattened (pass <c>post.Author</c> itself).</para>
	/// </remarks>
	/// <typeparam name="T">The type of the object whose members are the parameters.</typeparam>
	/// <param name="source">The object to read the values from.</param>
	/// <returns>This instance for use in method chaining.</returns>
	/// <exception cref="ArgumentNullException"><paramref name="source"/> is <see langword="null"/>.</exception>
	public TThis AddParams<T>(T source)
		where T : notnull
	{
		if (source is null) throw new ArgumentNullException(nameof(source));
		Contract.EndContractBlock();

		// A source typed object has no members of its own: its runtime type's are used (a Func<T, object> result, a boxed anonymous object).
		if (typeof(T) == typeof(object))
		{
			var members = RuntimeParamSource.Of(source.GetType());
			if (members.Names.Length == 0) return (TThis)this;

			// A new list is made at the size of the members, not at the default of four slots of a large struct.
			List<Param> own = _params ??= new(members.Names.Length);
			for (int i = 0; i < members.Names.Length; i++)
				own.Add(Param.OfObject(members.Names[i], members.Getters[i](source), members.Types[i]));

			_hasDerivedParams = true;
			return (TThis)this;
		}

		string[] names = ParamSource<T>.Names;
		Func<T, object?>[] getters = ParamSource<T>.Getters;
		Type[] types = ParamSource<T>.Types;
		if (names.Length == 0) return (TThis)this;

		List<Param> list = Params;
		for (int i = 0; i < names.Length; i++)
			list.Add(Param.OfObject(names[i], getters[i](source), types[i]));

		_hasDerivedParams = true;
		return (TThis)this;
	}

	TThis AddDerivedParam(object? value, string? expression, Type clrType)
	{
		// The facts of the expression are worked out once per expression string (see ParameterNames.Describe).
		if (ParameterNames.Describe(expression) is not { } described)
			throw NotDerivable(expression);

		// Name is the last member as written; the real name replaces it at execution when the procedure's names are known.
		Params.Add(Param.Derived(described.LastMember, expression!, value, clrType));
		_hasDerivedParams = true;
		return (TThis)this;
	}

	TThis CheckDerivable(string? expression)
		=> ParameterNames.IsDerivable(expression) ? (TThis)this : throw NotDerivable(expression);

	[SuppressMessage("Usage", "CA2208:Instantiate argument exceptions correctly")]
	static ArgumentException NotDerivable(string? expression)
		=> expression is null
			? new("The compiler did not supply the argument's text (deriving a name needs C# 10 or newer). Pass the name explicitly: AddParam(\"name\", value).", "value")
			: new($"Cannot derive a parameter name from the argument '{expression}'. Pass a variable or a chain of members such as filter.CompanySerialNum, or name the parameter: AddParam(\"name\", value).", "value");

