	/// <summary>
	/// Executes the command with a return parameter, as
	/// <see cref="IDbCommand.ExecuteNonQuery"/> does, and returns the value of
	/// that parameter.
	/// </summary>
	/// <returns>The value from the return parameter.</returns>
	internal object? ExecuteReturn()
		// The connection is opened before the command is created, as some commands require it.
		=> ExecuteCore(0, static (cmd, _, _) =>
		{
			IDbDataParameter returnParameter = cmd.AddReturnParameter();
			cmd.ExecuteNonQuery();
			return returnParameter.Value;
		});

	/// <summary>
	/// Executes the command with a return parameter, as
	/// <see cref="IDbCommand.ExecuteNonQuery"/> does, and returns the value of
	/// that parameter converted to <typeparamref name="T"/>.
	/// </summary>
	/// <typeparam name="T">The type to convert the value to.</typeparam>
	/// <returns>
	/// The value from the return parameter, converted to <typeparamref name="T"/> as <c>Map&lt;T&gt;()</c> converts a column: a value that is already a <typeparamref name="T"/> is returned as is, an integer is converted to another integer type with a range check, and any other value takes the general conversion.
	/// <see langword="default"/> when it is NULL.
	/// </returns>
	/// <exception cref="ValueMappingException">The value does not convert to <typeparamref name="T"/>, or is out of its range.</exception>
	internal T ExecuteReturn<T>()
		=> RowMap<T>.ConvertScalar(ExecuteReturn());

	/// <summary>
	/// Asynchronously executes the command with a return parameter, as
	/// <see cref="DbCommand.ExecuteNonQueryAsync(System.Threading.CancellationToken)"/> does,
	/// and returns the value of that parameter.
	/// </summary>
	/// <inheritdoc cref="ExecuteReturn()"/>
	/// <include file="Commands.docs.xml" path="docs/members[@name='token']/*" />
	/// <exception cref="OperationCanceledException">
	/// The command's token or <paramref name="cancellationToken"/> is already
	/// canceled; thrown before anything runs.
	/// </exception>
	public ValueTask<object?> ExecuteReturnAsync(
		CancellationToken cancellationToken = default)
	{
		// Thrown synchronously, as before:
		// both tokens are checked before anything is linked.
		CancellationToken.ThrowIfCancellationRequested();
		cancellationToken.ThrowIfCancellationRequested();

		return ExecuteCombinedAsync(cancellationToken, static async (cmd, _, token) =>
		{
			IDbDataParameter returnParameter = cmd.AddReturnParameter();

			if (cmd is DbCommand dbCommand)
				await dbCommand.ExecuteNonQueryAsync(token).ConfigureAwait(false);
			else
				cmd.ExecuteNonQuery();

			return returnParameter.Value;
		})!;
	}

	/// <summary>
	/// Asynchronously executes the command with a return parameter, as
	/// <see cref="DbCommand.ExecuteNonQueryAsync(System.Threading.CancellationToken)"/> does,
	/// and returns the value of that parameter converted to
	/// <typeparamref name="T"/>.
	/// </summary>
	/// <inheritdoc cref="ExecuteReturn{T}()"/>
	/// <include file="Commands.docs.xml" path="docs/members[@name='token']/*" />
	public async ValueTask<T> ExecuteReturnAsync<T>(
		CancellationToken cancellationToken = default)
		=> RowMap<T>.ConvertScalar(
			await ExecuteReturnAsync(cancellationToken).ConfigureAwait(false));

