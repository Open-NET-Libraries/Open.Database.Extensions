	/// <summary>
	/// Gets the names of the parameters a stored procedure declares, so a parameter added with <c>AddParam(value)</c> can be matched to the real one.
	/// A provider that can look this up overrides it (<see cref="ExpressiveDbCommand"/> and <see cref="ExpressiveCommand"/> ask the ADO.NET schema collection <c>ProcedureParameters</c> of a <see cref="DbConnection"/>); the default returns nothing, and the last member of each argument is used as written.
	/// </summary>
	/// <remarks>
	/// Return the names exactly as the provider spells them: a leading <c>@</c> is ignored when matching, nothing else is changed, and the name that is sent is the one returned.
	/// An empty or default array means "not known", which also covers a procedure that declares no parameters. It is remembered for 15 seconds, not the five minutes of known names, and replaces any older names of that procedure.
	/// </remarks>
	/// <param name="connection">An open connection to run the lookup on. A command that executes inside a transaction must use <see cref="Transaction"/>.</param>
	/// <param name="procedure">The procedure name as given to the command.</param>
	/// <returns>The names as the provider reports them (a leading <c>@</c> is fine), or an empty or default array when they are not known.</returns>
	protected virtual ImmutableArray<string> GetProcedureParameterNames(TConnection connection, string procedure)
		=> default;

	/// <summary>Asynchronously gets the names of the parameters a stored procedure declares. See <see cref="GetProcedureParameterNames"/>.</summary>
	/// <param name="connection">An open connection to run the lookup on.</param>
	/// <param name="procedure">The procedure name as given to the command.</param>
	/// <param name="cancellationToken">The cancellation token of the call: the command's cancellation token, together with the one passed to the terminal (for example <c>ToListAsync(token)</c>) when there is one.</param>
	/// <returns>The names as the provider reports them, or an empty or default array when they are not known.</returns>
	protected virtual ValueTask<ImmutableArray<string>> GetProcedureParameterNamesAsync(TConnection connection, string procedure, CancellationToken cancellationToken)
		=> new(GetProcedureParameterNames(connection, procedure));

	/// <summary>
	/// Finds the names the connection's procedure declares, or the
	/// <c>@name</c> markers of the text.
	/// </summary>
	/// <remarks>
	/// Runs in every run of a command that has derived names, after the
	/// connection is open and before the command is built; nothing is written
	/// to <see cref="Params"/>.
	/// What is remembered is a <c>NameSet</c> (the names and the match found
	/// for each argument), so a repeat execution allocates nothing to resolve.
	/// </remarks>
	/// <param name="connection">An open connection to run the lookup on.</param>
	/// <returns>
	/// The set of names, or <see langword="null"/> when they are not known.
	/// </returns>
	NameSet? ResolveDerivedNames(TConnection connection)
	{
		if (Type == CommandType.StoredProcedure)
		{
			ProcedureKey key = ProcedureKey(connection);
			bool found = ProcedureNameCache.TryGet(
				NameCacheOwner,
				key,
				out NameSet? remembered);
			if (found && Fits(remembered)) return remembered;

			// Nothing is remembered, or the remembered names did not fit:
			// the procedure may have changed since they were read.
			return Remember(
				key,
				GetProcedureParameterNames(connection, Command),
				found);
		}

		// The @name markers found in the text.
		return Type == CommandType.Text
			? TextNameCache.Get(Command)
			: null;
	}

	/// <summary>
	/// Asynchronously finds the names the connection's procedure declares, or
	/// the <c>@name</c> markers of the text.
	/// </summary>
	/// <remarks>
	/// Not an <see langword="async"/> method itself: when the names are
	/// remembered (the usual case) it finishes without a state machine or an
	/// <see langword="await"/>; only reading them is asynchronous.
	/// </remarks>
	/// <param name="connection">An open connection to run the lookup on.</param>
	/// <param name="cancellationToken">The token that governs the call.</param>
	/// <returns>
	/// The set of names, or <see langword="null"/> when they are not known.
	/// </returns>
	ValueTask<NameSet?> ResolveDerivedNamesAsync(
		TConnection connection,
		CancellationToken cancellationToken)
	{
		if (Type == CommandType.StoredProcedure)
		{
			ProcedureKey key = ProcedureKey(connection);
			bool found = ProcedureNameCache.TryGet(
				NameCacheOwner,
				key,
				out NameSet? remembered);
			return found && Fits(remembered)
				? new(remembered)
				: ReadNamesAsync(connection, key, found, cancellationToken);
		}

		// The @name markers found in the text.
		return new(
			Type == CommandType.Text
				? TextNameCache.Get(Command)
				: null);
	}

	async ValueTask<NameSet?> ReadNamesAsync(
		TConnection connection,
		ProcedureKey key,
		bool afterMiss,
		CancellationToken cancellationToken)
		=> Remember(
			key,
			await GetProcedureParameterNamesAsync(
					connection,
					Command,
					cancellationToken)
				.ConfigureAwait(false),
			afterMiss);

	TCommand PrepareResolved(TConnection connection)
		=> _hasDerivedParams
			? PrepareDerived(connection, ResolveDerivedNames(connection))
			: PrepareWritten(connection);

	NameSet? WrittenNames()
	{
		if (_params is not { Count: > 0 } || Type != CommandType.Text || Command is not { Length: > 0 } text) return null;

		return TextNameCache.Get(text) is { Names.Length: > 0 } names ? names : null;
	}

	// The count of @names the text declares (one slot each), else the default growth.
	int ScannedCount()
		=> Type == CommandType.Text && Command is { Length: > 0 } text && TextNameCache.Get(text) is { Names.Length: > 0 } names
			? names.Names.Length
			: 0;

	TCommand PrepareWritten(TConnection connection)
		=> WrittenNames() is { } text
			? PrepareDerived(connection, text, written: true)
			: PrepareCommand(connection);

	/// <summary>
	/// Builds the send list, sets up the command and resets, in one
	/// synchronous stretch.
	/// </summary>
	/// <remarks>
	/// Never across an <see langword="await"/>, as the list belongs to this
	/// thread.
	/// The caller's <see cref="Params"/> are not touched, so the next run
	/// (on another database, say) starts from what was added.
	/// </remarks>
	/// <param name="connection">The connection to create the command from.</param>
	/// <param name="names">The set of names the parameters are matched to.</param>
	/// <param name="written">
	/// <see langword="true"/> for a command that has no derived names, where only a written name that the text spells differently is resolved.
	/// </param>
	/// <returns>The new command to use.</returns>
	TCommand PrepareDerived(TConnection connection, NameSet? names, bool written = false)
	{
		// Taken out of the spare slot, so a hook that sets up another
		// command on this thread builds its own list.
		List<Param> send = _spareList ?? new(_params!.Count);
		_spareList = null;
		object? outerCommand = _preparing;
		List<Param>? outerList = _sendList;
		try
		{
			if (written) ResolveWritten(send, names!);
			else BuildSendList(send, names);
			_preparing = this;
			_sendList = send;
			return PrepareCommand(connection);
		}
		finally
		{
			_preparing = outerCommand;
			_sendList = outerList;
			send.Clear();
			_spareList = send;
		}
	}

	/// <summary>
	/// Remembers the names a procedure reported and returns the set made from
	/// them.
	/// </summary>
	/// <remarks>
	/// An empty answer is "not known" (<see langword="null"/>): it is
	/// remembered for a short while (so an unreadable procedure is not read
	/// again in every run), and it replaces an older entry, which the answer
	/// has outdated.
	/// </remarks>
	/// <param name="key">The server, database and procedure the names belong to.</param>
	/// <param name="names">The names as the provider reported them.</param>
	/// <param name="afterMiss">
	/// <see langword="true"/> when the names were read again because the
	/// remembered ones did not fit: the set made is a second look
	/// (see <c>NameSet.Rechecked</c>).
	/// </param>
	/// <returns>
	/// The set made from the names, or <see langword="null"/> for an empty answer.
	/// </returns>
	NameSet? Remember(
		ProcedureKey key,
		ImmutableArray<string> names,
		bool afterMiss)
	{
		if (!names.IsDefaultOrEmpty)
		{
			return ProcedureNameCache.Set(
				NameCacheOwner,
				key,
				names,
				afterMiss);
		}

		ProcedureNameCache.SetUnknown(NameCacheOwner, key);
		return null;
	}

	/// <summary>
	/// Gets the object that remembered names belong to: the object commands
	/// take connections from.
	/// </summary>
	/// <remarks>
	/// That is a factory (not the wrapper made around it for each command),
	/// a pool, or the bare connection.
	/// </remarks>
	object NameCacheOwner => _poolOrConnection switch
	{
		DbConnectionFactoryExtensions.ConnectionFactoryToPoolAdapter<TConnection> typed => typed.Identity,
		DbConnectionFactoryExtensions.ConnectionFactoryToPoolAdapter untyped => untyped.Identity,
		_ => _poolOrConnection,
	};

	/// <summary>
	/// Makes the key a procedure's names are remembered under.
	/// </summary>
	/// <remarks>
	/// The server and the database are part of the key: one connection can be
	/// switched to another database, and one factory can hand out connections
	/// to different servers, where the same procedure name may be a different
	/// procedure.
	/// <see cref="IDbConnection"/> has no server name, so a connection that is
	/// not a <see cref="DbConnection"/> contributes none.
	/// The key is a struct of the three parts, so no string is built.
	/// </remarks>
	/// <param name="connection">The connection the procedure is looked up on.</param>
	/// <returns>The key of <see cref="Command"/> on that connection.</returns>
	ProcedureKey ProcedureKey(TConnection connection) => new((connection as DbConnection)?.DataSource, connection.Database, Command);

	/// <summary>
	/// Determines whether the remembered names still fit the arguments.
	/// </summary>
	/// <remarks>
	/// <para>
	/// <see langword="false"/> when an argument named by the caller matches
	/// none of the remembered names, or when a member of an
	/// <c>AddParams</c> object matches none and the names are a first look
	/// (not <c>Rechecked</c>): the procedure may have changed since they were
	/// read, so they are read again before anything is dropped.
	/// A set that is already a second look drops such a member without
	/// another read, so a member the procedure never takes does not cost a
	/// read in every run.
	/// </para>
	/// <para>
	/// Nothing is built or kept, so a <see langword="false"/> answer leaves
	/// no state behind.
	/// </para>
	/// </remarks>
	/// <param name="real">
	/// The remembered names.
	/// It has no names when they are not known (<see langword="null"/>, or
	/// the shared "not known" set) and for a text without markers:
	/// each argument then keeps its last member as written.
	/// </param>
	/// <returns>
	/// <see langword="true"/> if the names fit; otherwise,
	/// <see langword="false"/>.
	/// </returns>
	bool Fits(NameSet? real)
	{
		if (real is not { Names.Length: > 0 }) return true;

		List<Param> list = _params!;
		for (int i = 0; i < list.Count; i++)
		{
			Param p = list[i];
			if (p.Expression is not { } expression
			 || p.FromObject && real.Rechecked)
			{
				continue;
			}

			if (real.Match(expression, Command) is null) return false;
		}

		return true;
	}

	/// <summary>
	/// Builds, in <paramref name="send"/>, what one run of a command with written names sends: each name that the text declares
	/// with a different spelling (without its <c>@</c>, say) under the text's own spelling, the rest as written.
	/// </summary>
	/// <param name="send">The list to fill.</param>
	/// <param name="text">The names the text declares.</param>
	void ResolveWritten(List<Param> send, NameSet text)
	{
		List<Param> list = _params!;
		for (int i = 0; i < list.Count; i++)
		{
			Param p = list[i];
			if (p.Expression is not null || text.Find(p.Name) is not { } entry)
			{
				send.Add(p);
				continue;
			}

			// Two spellings of one name that the text declares are both sent as written, as they always were.
			bool collides = false;
			for (int j = 0; j < i; j++)
			{
				if (list[j].Expression is null && !string.Equals(list[j].Name, p.Name, StringComparison.Ordinal) && text.Find(list[j].Name) is { } earlier && SameName(entry.Real, earlier.Real))
				{
					send[j] = list[j];
					collides = true;
				}
			}

			send.Add(collides || string.Equals(entry.Real, p.Name, StringComparison.Ordinal) ? p : p.Resolved(entry.Real));
		}
	}

	/// <summary>
	/// Builds, in <paramref name="send"/>, what one run sends: the caller's
	/// parameters under their resolved names, in order.
	/// </summary>
	/// <remarks>The caller's list (<see cref="_params"/>) is only read.</remarks>
	/// <param name="send">The list to fill.</param>
	/// <param name="real">The remembered names, or <see langword="null"/> when they are not known.</param>
	void BuildSendList(List<Param> send, NameSet? real)
	{
		List<Param> list = _params!;
		int count = list.Count;

		// The name each parameter ends up with (null: not sent), in a pooled array; only the used part is cleared when it goes back.
		string?[] names = ArrayPool<string?>.Shared.Rent(count);
		try
		{
			Apply(list, count, names, real, send);
		}
		finally
		{
			Array.Clear(names, 0, count);
			ArrayPool<string?>.Shared.Return(names);
		}
	}

	void Apply(
		List<Param> list,
		int count,
		string?[] names,
		NameSet? real,
		List<Param> send)
	{
		// A text command without a remembered set (one that is not an interned string) has its markers scanned for each argument (see TextNameCache).
		bool scan = real is null && Type == CommandType.Text;
		bool known = scan ? TextNameCache.HasMarkers(Command) : real is { Names.Length: > 0 };

		// Resolve each name. Without the real names the last member is used as written.
		for (int i = 0; i < count; i++)
		{
			Param p = list[i];
			if (p.Expression is not { } expression)
			{
				// A name written without its @ goes under the spelling a text command declares.
				names[i] = Type == CommandType.Text && real is { Names.Length: > 0 } && real.Find(p.Name) is { } declared
					? declared.Real
					: p.Name;
				continue;
			}

			string? name = !known
				? p.Name
				: scan
					? TextNameCache.Scan(Command, expression)
					: real!.Match(expression, Command);
			if (name is null)
			{
				// A member of an object that the procedure does not take is simply not sent; an argument named by the caller must match.
				if (p.FromObject) { names[i] = null; continue; } // the pooled slot holds whatever an earlier renter left: write it before it is read

				throw NoMatch(expression, scan ? TextNameCache.Names(Command) : real!.Names);
			}

			names[i] = name;
		}

		// A parameter named by the caller wins over a member of an object that resolves to the same name.
		// The ones compared against are never members of an object, so dropping a member does not change the answer for another.
		for (int i = 0; i < count; i++)
		{
			if (names[i] is not { } member || !list[i].FromObject) continue;
			for (int j = 0; j < count; j++)
			{
				if (j != i && names[j] is { } other && !list[j].FromObject && SameName(member, other))
				{
					names[i] = null;
					break;
				}
			}
		}

		// Two arguments that resolve to one parameter would silently overwrite each other.
		for (int i = 0; i < count; i++)
		{
			if (names[i] is not { } first) continue;
			for (int j = i + 1; j < count; j++)
			{
				if (names[j] is { } second && SameName(first, second))
					throw Collision(first, list[i], list[j], scan ? TextNameCache.Names(Command) : real?.Names ?? default);
			}
		}

		// What is sent, in order, under its resolved name.
		for (int i = 0; i < count; i++)
		{
			if (names[i] is not { } name) continue;
			Param p = list[i];
			send.Add(p.Expression is null && string.Equals(name, p.Name, StringComparison.Ordinal) ? p : p.Resolved(name));
		}
	}

	static bool SameName(string a, string b) => Bare(a).Equals(Bare(b), StringComparison.OrdinalIgnoreCase);

	static ReadOnlySpan<char> Bare(string name) => name.Length > 0 && name[0] == '@' ? name.AsSpan(1) : name.AsSpan();

	/// <summary>
	/// Describes what the caller wrote for a parameter, for the message of a
	/// collision.
	/// </summary>
	/// <param name="original">The parameter as added.</param>
	/// <returns>The description.</returns>
	static string Written(Param original)
		=> original.Expression is { } expression
			? original.FromObject ? $"the member '{expression}' of the AddParams object" : $"the argument '{expression}'"
			: $"the name '{original.Name}' you passed";

	InvalidOperationException Collision(string name, Param first, Param second, ImmutableArray<string> real)
		=> new($"Two parameters resolve to '{name}': {Written(first)} and {Written(second)}. "
			+ (real.IsDefaultOrEmpty
				? "The parameter names are not known, so each argument is used under its last member as written."
				: $"The procedure '{Command}' declares: {string.Join(", ", real)}.")
			+ " Name one of them explicitly: AddParam(\"name\", value).");

	InvalidOperationException NoMatch(string expression, ImmutableArray<string> real)
		=> new($"The argument '{expression}' matches none of the parameters of '{Command}' (tried {string.Join(", ", ParameterNames.Candidates(expression))}). The procedure declares: {string.Join(", ", real)}. Name the parameter explicitly: AddParam(\"name\", value).");

