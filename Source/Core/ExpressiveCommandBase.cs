	/// <summary>
	/// Runs a function on a command built on a connection from the source,
	/// synchronously.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Every execution path funnels through this method and
	/// <c>ExecuteCoreAsync</c>: take the connection, make sure it is open,
	/// build the command, run the caller's function, release the connection.
	/// The caller's inputs travel in <typeparamref name="TState"/> (a value
	/// type for the typed paths) and the functions are static lambdas, so a
	/// call allocates no closures or delegates of its own.
	/// </para>
	/// <para>
	/// The connection is opened before the command is created, as some
	/// <see cref="IDbCommand"/> implementations require it.
	/// </para>
	/// </remarks>
	/// <typeparam name="TState">The type of the state passed to the function.</typeparam>
	/// <typeparam name="TResult">The type of the result.</typeparam>
	/// <param name="state">The state to pass to the function.</param>
	/// <param name="func">
	/// The function to run, given the command, the state of the connection
	/// before it was opened, and <paramref name="state"/>.
	/// </param>
	/// <returns>The result of <paramref name="func"/>.</returns>
	private protected TResult ExecuteCore<TState, TResult>(TState state, Func<TCommand, ConnectionState, TState, TResult> func)
	{
		if (_poolOrConnection is TConnection single)
			return ExecuteDirect(single, state, func);

		// Take, open if needed, give back when done (the pool decides what that means).
		var pool = (IDbConnectionPool<TConnection>)_poolOrConnection;
		using var lease = pool.EnsureOpenScope();
		using TCommand cmd = PrepareResolved(lease.Connection);
		return func(cmd, lease.PriorState, state);
	}

	/// <summary>
	/// Runs a function asynchronously, for the terminals that take a token.
	/// </summary>
	/// <remarks>
	/// The token is used together with the command's own, and either cancels.
	/// The function is given the token that governs the call.
	/// </remarks>
	/// <typeparam name="TResult">The type of the result.</typeparam>
	/// <param name="callToken">The token passed to the terminal.</param>
	/// <param name="func">The function to run.</param>
	/// <returns>A task that represents the asynchronous operation; its result is the result of <paramref name="func"/>.</returns>
	[SuppressMessage(
		"Design", "CA1068:CancellationToken parameters must come last")]
	private protected ValueTask<TResult> ExecuteCombinedAsync<TResult>(
		CancellationToken callToken,
		Func<TCommand, ConnectionState, CancellationToken, ValueTask<TResult>> func)
		=> CancellationTokens.RunAsync(
			CancellationToken,
			callToken,
			(self: this, func),
			static (s, token) => s.self.ExecuteCoreAsync(token, s.func, token));

	private protected ValueTask<TResult> ExecuteCoreAsync<TState, TResult>(TState state, Func<TCommand, ConnectionState, TState, ValueTask<TResult>> func)
		=> ExecuteCoreAsync(state, func, CancellationToken);

	/// <summary>
	/// Runs a function on a command built on a connection from the source,
	/// asynchronously.
	/// </summary>
	/// <remarks>
	/// The token governs the whole call: the first check, the connection open,
	/// the name lookup, and (through the state, which the caller builds) the
	/// execute and the reads.
	/// </remarks>
	/// <typeparam name="TState">The type of the state passed to the function.</typeparam>
	/// <typeparam name="TResult">The type of the result.</typeparam>
	/// <param name="state">The state to pass to the function.</param>
	/// <param name="func">The function to run.</param>
	/// <param name="cancellationToken">The token that governs the call.</param>
	/// <returns>A task that represents the asynchronous operation; its result is the result of <paramref name="func"/>.</returns>
	/// <exception cref="OperationCanceledException">
	/// <paramref name="cancellationToken"/> is already canceled.
	/// </exception>
	private protected async ValueTask<TResult> ExecuteCoreAsync<TState, TResult>(TState state, Func<TCommand, ConnectionState, TState, ValueTask<TResult>> func, CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested(); // Since cancelled awaited tasks throw, we will follow the same pattern here.

		if (_poolOrConnection is TConnection single)
		{
			using Busy busy = EnterDirect();
			var direct = await EnsureOpenScopeUnlessOpenAsync(
					single,
					null,
					cancellationToken)
				.ConfigureAwait(false);
			await using var directDisposal = direct.ConfigureAwait(false);
			NameSet? names = null;
			if (_hasDerivedParams)
			{
				names = await ResolveDerivedNamesAsync(
						single,
						cancellationToken)
					.ConfigureAwait(false);
			}

			using TCommand cmd = _hasDerivedParams
				? PrepareDerived(single, names)
				: PrepareWritten(single);
			return await func(cmd, direct.PriorState, state).ConfigureAwait(false);
		}

		var pool = (IDbConnectionPool<TConnection>)_poolOrConnection;
		var lease = await EnsureOpenScopeUnlessOpenAsync(
				pool.Take(),
				pool,
				cancellationToken)
			.ConfigureAwait(false);
		await using var leaseDisposal = lease.ConfigureAwait(false);
		NameSet? leaseNames = null;
		if (_hasDerivedParams)
		{
			leaseNames = await ResolveDerivedNamesAsync(lease.Connection, cancellationToken)
				.ConfigureAwait(false);
		}

		using TCommand leaseCommand = _hasDerivedParams
			? PrepareDerived(lease.Connection, leaseNames)
			: PrepareWritten(lease.Connection);
		return await func(leaseCommand, lease.PriorState, state).ConfigureAwait(false);
	}

	/// <summary>
	/// Gets the scope of a connection taken from a pool (given back when it is
	/// disposed) or, with no pool, the caller's own (closed again if it was
	/// opened here).
	/// </summary>
	/// <remarks>
	/// An open connection (the usual case) needs no awaiting at all.
	/// </remarks>
	/// <param name="connection">The connection.</param>
	/// <param name="pool">The pool it was taken from, or <see langword="null"/>.</param>
	/// <param name="cancellationToken">The token that governs the call.</param>
	/// <returns>A task that represents the asynchronous operation; its result is the scope.</returns>
	static ValueTask<ConnectionScope<TConnection>> EnsureOpenScopeUnlessOpenAsync(
		TConnection connection,
		IDbConnectionPool<TConnection>? pool,
		CancellationToken cancellationToken)
	{
		ConnectionState state = connection.State;
		if ((state & (ConnectionState.Open | ConnectionState.Broken)) == ConnectionState.Open)
		{
			return new ValueTask<ConnectionScope<TConnection>>(
				pool is null
					? new ConnectionScope<TConnection>(connection, state)
					: new ConnectionScope<TConnection>(connection, state, pool));
		}

		return pool is null
			? connection.EnsureOpenScopeAsync(cancellationToken)
			: ConnectionExtensions.OpenOwnedAsync(connection, pool, cancellationToken);
	}

	TResult ExecuteDirect<TState, TResult>(TConnection single, TState state, Func<TCommand, ConnectionState, TState, TResult> func)
	{
		using Busy busy = EnterDirect();
		using var direct = single.EnsureOpenScope();
		using TCommand cmd = PrepareResolved(single);
		return func(cmd, direct.PriorState, state);
	}

	/// <summary>
	/// Takes the guard of a single connection, which is for one run at a time.
	/// </summary>
	/// <remarks>
	/// The guard is what the run holds while it uses the connection, and
	/// disposing it lets the next run in; a connection that was closed when
	/// the run began is closed again by its own scope, before this lets go.
	/// </remarks>
	/// <returns>The guard.</returns>
	/// <exception cref="InvalidOperationException">Another run holds the connection.</exception>
	Busy EnterDirect()
	{
		if (Interlocked.CompareExchange(ref _busy, 1, 0) != 0)
			throw new InvalidOperationException("Concurrent use of a single connection is not supported.");

		return new Busy(this);
	}

	readonly struct Busy(
		ExpressiveCommandBase<TConnection, TCommand, TReader, TDbType, TThis> owner)
		: IDisposable
	{
		public void Dispose() => Volatile.Write(ref owner._busy, 0);
	}

